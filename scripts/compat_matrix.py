'''Run the test suite on a matrix of Python and numpy versions.

Each cell is a fresh, isolated environment built by `uv` with exactly the given
Python and numpy (wheels only), plus `pytest` and a compatible `scipy`. The
`uv.lock` and `pyproject.toml` are not touched. Graphics tests are skipped,
as the `graphics` extra is not installed.

Cells are all numpy minors from the floor in `pyproject.toml` on (latest patch,
plus the floor itself) combined with every Python in `PYTHONS` that has a numpy
wheel. Cells run one after another: parallel runs race in the `uv` cache on Windows.

Usage, from the repository root:

    uv run --no-project --python 3.12 python scripts/compat_matrix.py --list
    uv run --no-project --python 3.12 python scripts/compat_matrix.py --python 3.12 --numpy 2.0
    uv run --no-project --python 3.12 python scripts/compat_matrix.py --update-readme
'''
import argparse
import datetime
import json
import platform
import re
import subprocess
import sys
import time
import tomllib
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
README = ROOT / 'README.md'
START, END = '<!-- compat-matrix:start -->', '<!-- compat-matrix:end -->'

# Update when a new Python is released and available through `uv python list`
PYTHONS = ['3.9', '3.10', '3.11', '3.12', '3.13', '3.14']


def version_tuple(v: str) -> tuple[int, ...]:
    return tuple(int(x) for x in v.split('.'))

def project() -> dict:
    return tomllib.loads((ROOT / 'pyproject.toml').read_text(encoding='utf-8'))['project']

def numpy_floor() -> str:
    for dep in project()['dependencies']:
        m = re.fullmatch(r'numpy\s*>=\s*([\d.]+)', dep.split(';')[0].strip())
        if m:
            return m.group(1)
    raise SystemExit('No `numpy>=X` dependency found in pyproject.toml')

def numpy_releases(floor: str) -> dict[str, set[str]]:
    '''{version: {'3.9', ...}} for the floor and the latest patch of each later minor, from PyPI wheels'''
    with urllib.request.urlopen('https://pypi.org/pypi/numpy/json', timeout=60) as response:
        releases = json.load(response)['releases']

    def pythons(files: list) -> set[str]:
        tags = {f['python_version'] for f in files if f['packagetype'] == 'bdist_wheel'}
        return {f'3.{t[3:]}' for t in tags if re.fullmatch(r'cp3\d+', t)}

    latest = {}
    for v, files in releases.items():
        if not re.fullmatch(r'\d+\.\d+\.\d+', v) or not files or version_tuple(v) < version_tuple(floor):
            continue
        minor = version_tuple(v)[:2]
        if minor not in latest or version_tuple(v) > version_tuple(latest[minor]):
            latest[minor] = v

    selected = {floor, *latest.values()}
    return {v: pythons(releases[v]) for v in sorted(selected, key=version_tuple)}

def run_cell(python: str, numpy: str) -> tuple[str, str]:
    '''(status, pytest summary line)'''
    command = ['uv', 'run', '--quiet', '--no-project', '--isolated', '--python', python,
               '--no-build-package', 'numpy', '--no-build-package', 'scipy',
               '--with', f'numpy=={numpy}', '--with', 'pytest', '--with', 'scipy',
               '--with-editable', str(ROOT),
               'pytest', '-q', '-p', 'no:cacheprovider', str(ROOT / 'tests')]
    result = subprocess.run(command, cwd=ROOT, capture_output=True, text=True, encoding='utf-8', errors='replace')
    lines = (result.stdout + result.stderr).strip().splitlines()
    summary = next((l.strip('= ') for l in reversed(lines)
                    if re.search(r'\d+ (passed|failed|error)', l)), lines[-1] if lines else '')
    if result.returncode == 0:
        return 'pass', summary
    if re.search(r'\d+ (passed|failed|error)', summary):
        return 'fail', summary
    return 'error', summary

def markdown_table(results: dict, versions: list[str], pythons: list[str], wheels: dict) -> str:
    symbol = {'pass': '✅', 'fail': '❌', 'error': '⚠️'}
    lines = ['| numpy \\ Python | ' + ' | '.join(pythons) + ' |',
             '|---|' + '---|'*len(pythons)]
    for v in versions:
        cells = []
        for py in pythons:
            if py not in wheels[v]:
                cells.append('')
            else:
                cells.append(symbol.get(results.get((py, v), ('',))[0], '·'))
        lines.append(f'| {v} | ' + ' | '.join(cells) + ' |')
    return '\n'.join(lines)

def update_readme(table: str):
    text = README.read_text(encoding='utf-8')
    if START not in text or END not in text:
        raise SystemExit(f'README.md lacks the {START} ... {END} markers')
    stamp = (f'_Generated by `scripts/compat_matrix.py` for spinwaves {project()["version"]} on '
             f'{datetime.date.today().isoformat()}, {platform.system()} {platform.machine()}. '
             f'✅ all tests pass, ❌ failing tests, ⚠️ environment could not be built, '
             f'empty: no numpy wheel for that Python._')
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    README.write_text(f'{head}{START}\n{table}\n\n{stamp}\n{END}{tail}', encoding='utf-8', newline='\n')
    print(f'Updated {README}')


def main():
    sys.stdout.reconfigure(encoding='utf-8', errors='replace')     # Windows consoles default to cp1252
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--python', nargs='*', default=PYTHONS, help='Python versions, default: %(default)s')
    parser.add_argument('--numpy', nargs='*', help='numpy versions or minors (e.g. 2.0), default: all from the floor')
    parser.add_argument('--list', action='store_true', help='only list the cells')
    parser.add_argument('--update-readme', action='store_true', help='write the table into README.md')
    args = parser.parse_args()

    floor = numpy_floor()
    wheels = numpy_releases(floor)
    versions = list(wheels)
    if args.numpy:
        versions = [v for v in versions if any(v == n or v.startswith(n + '.') for n in args.numpy)]
    cells = [(py, v) for v in versions for py in args.python if py in wheels[v]]

    print(f'numpy floor {floor}; {len(cells)} cells')
    if args.list:
        for py, v in cells:
            print(f'  python {py:5s} numpy {v}')
        return

    results = {}
    for i, (py, v) in enumerate(cells, 1):
        t0 = time.perf_counter()
        results[(py, v)] = run_cell(py, v)
        status, summary = results[(py, v)]
        print(f'[{i:2d}/{len(cells)}] python {py:5s} numpy {v:7s} {status:5s} {summary}  ({time.perf_counter()-t0:.0f} s)',
              flush=True)

    table = markdown_table(results, versions, args.python, wheels)
    print('\n' + table)
    if args.update_readme:
        update_readme(table)
    sys.exit(0 if all(s == 'pass' for s, _ in results.values()) else 1)

if __name__ == '__main__':
    main()
